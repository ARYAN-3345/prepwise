def seed_syllabus():
    """Keep topics aligned with the source syllabus, retaining historical rows."""
    Topic.query.update({Topic.is_active: False}, synchronize_session=False)
    for subject, names in SYLLABUS.items():
        for order, name in enumerate(names):
            topic = Topic.query.filter_by(subject=subject, name=name).first()
            if topic is None:
                topic = Topic(subject=subject, name=name)
                db.session.add(topic)
            topic.order_index = order
            topic.is_active = True
    db.session.commit()
